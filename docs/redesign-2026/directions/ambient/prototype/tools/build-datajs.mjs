// Rebuilds data.js (data.json + palettes.json as window.AG_DATA) without needing the Phosphor assets that
// build-assets.mjs wants. fetch() of a sibling file is blocked on file://, so the prototype loads data.js.
// Run from the repo root:  node docs/redesign-2026/directions/ambient/prototype/tools/build-datajs.mjs
import fs from 'node:fs';
import path from 'node:path';
const dir = path.join(process.cwd(), 'docs/redesign-2026/directions/ambient/prototype');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'data.json'), 'utf8'));
data.palettes = JSON.parse(fs.readFileSync(path.join(dir, 'palettes.json'), 'utf8'));
fs.writeFileSync(path.join(dir, 'data.js'), `/* generated by tools/build-assets.mjs: data.json + palettes.json */\nwindow.AG_DATA=${JSON.stringify(data)};\n`);
console.log('data.js', fs.statSync(path.join(dir, 'data.js')).size, 'bytes;', data.subjects.map((s) => s.arts.length).join(','), 'arts per subject');

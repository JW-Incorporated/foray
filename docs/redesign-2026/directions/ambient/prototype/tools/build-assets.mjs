// Generates the three machine-written files the prototype loads:
//   icons.svg  the Phosphor (MIT) sprite plus our three custom glyphs
//   icons.js   the same sprite as a string, injected into the page (an external <use> is blocked on file://)
//   data.js    data.json + palettes.json as window.AG_DATA (fetch() of a sibling file is blocked on file://)
// Run from the repo root:
//   node docs/redesign-2026/directions/ambient/prototype/tools/build-assets.mjs <path to @phosphor-icons/core/assets>
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const dir = path.join(root, 'docs/redesign-2026/directions/ambient/prototype');
const assets = process.argv[2];

const MAP = [
  ['i-house', 'regular', 'house'], ['i-house-fill', 'fill', 'house-fill'],
  ['i-compass', 'regular', 'compass'], ['i-compass-fill', 'fill', 'compass-fill'],
  ['i-books', 'regular', 'books'], ['i-books-fill', 'fill', 'books-fill'],
  ['i-skip-next', 'regular', 'skip-forward'],
  ['i-bookmark', 'regular', 'bookmark-simple'], ['i-bookmark-fill', 'fill', 'bookmark-simple-fill'],
  ['i-check-circle', 'regular', 'check-circle'], ['i-check-circle-fill', 'fill', 'check-circle-fill'],
  ['i-download', 'regular', 'arrow-circle-down'], ['i-download-fill', 'fill', 'arrow-circle-down-fill'],
  ['i-queue', 'regular', 'list-plus'], ['i-dots', 'regular', 'dots-three'],
  ['i-chevron-left', 'regular', 'caret-left'], ['i-chevron-right', 'regular', 'caret-right'], ['i-chevron-down', 'regular', 'caret-down'],
  ['i-magnifier', 'regular', 'magnifying-glass'], ['i-x', 'regular', 'x'], ['i-share', 'regular', 'share-network'],
  ['i-moon', 'regular', 'moon'], ['i-gauge', 'regular', 'gauge'], ['i-sliders', 'regular', 'sliders-horizontal'],
  ['i-gear', 'regular', 'gear-six'], ['i-wifi-slash', 'regular', 'wifi-slash'], ['i-sparkle', 'regular', 'sparkle'],
  ['i-car', 'regular', 'car'], ['i-arrow-up', 'regular', 'arrow-up'], ['i-play-fill', 'fill', 'play-fill'], ['i-plus', 'regular', 'plus'],
  ['i-arrow-down', 'regular', 'arrow-down'], ['i-trash', 'regular', 'trash'],
];
const symbols = [];
for (const [id, weight, file] of MAP) {
  const svg = fs.readFileSync(path.join(assets, weight, file + '.svg'), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  symbols.push(`<symbol id="${id}" viewBox="0 0 256 256">${inner}</symbol>`);
}

// ---- custom glyphs, same 256 grid (BUILD-NOTES 2) ----
const play = '<symbol id="i-play" viewBox="0 0 256 256"><polygon points="96,62 96,194 200,128" fill="currentColor" stroke="currentColor" stroke-width="26" stroke-linejoin="round"/></symbol>';
const pause = '<symbol id="i-pause" viewBox="0 0 256 256"><rect x="72" y="52" width="40" height="152" rx="12" fill="currentColor"/><rect x="144" y="52" width="40" height="152" rx="12" fill="currentColor"/></symbol>';
const R = 84, deg = Math.PI / 180;
const P = (t, mirror) => { const x = 128 + R * Math.cos(t * deg); return [mirror ? 256 - x : x, 128 + R * Math.sin(t * deg)]; };
function skip(id, label, mirror) {
  // 270 degree arc, open at the top; arrowhead on the open end. Back: ccw head at -60. Forward: mirror image.
  const [sx, sy] = P(-60, mirror), [ex, ey] = P(-150, mirror);
  const sweep = mirror ? 0 : 1;
  const th = -60;
  let dx = Math.sin(th * deg), dy = -Math.cos(th * deg); if (mirror) dx = -dx;
  const px = -dy, py = dx;
  const tip = [sx + dx * 24, sy + dy * 24], b1 = [sx - dx * 6 + px * 20, sy - dy * 6 + py * 20], b2 = [sx - dx * 6 - px * 20, sy - dy * 6 - py * 20];
  const f = (n) => Math.round(n * 10) / 10;
  return `<symbol id="${id}" viewBox="0 0 256 256"><path d="M${f(sx)} ${f(sy)}A${R} ${R} 0 1 ${sweep} ${f(ex)} ${f(ey)}" fill="none" stroke="currentColor" stroke-width="22" stroke-linecap="round"/><polygon points="${f(tip[0])},${f(tip[1])} ${f(b1[0])},${f(b1[1])} ${f(b2[0])},${f(b2[1])}" fill="currentColor" stroke="currentColor" stroke-width="8" stroke-linejoin="round"/><text x="128" y="156" text-anchor="middle" font-family="DM Sans, system-ui, sans-serif" font-weight="600" font-size="84" fill="currentColor" stroke="none">${label}</text></symbol>`;
}
symbols.push(play, pause, skip('i-back15', '15', false), skip('i-fwd30', '30', true));

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">${symbols.join('')}</svg>`;
fs.writeFileSync(path.join(dir, 'icons.svg'), sprite.replace(' style="position:absolute"', '') + '\n');
fs.writeFileSync(path.join(dir, 'icons.js'), `/* generated by tools/build-assets.mjs: the sprite as a string */\nwindow.AG_SPRITE=${JSON.stringify(sprite)};\n`);

const data = JSON.parse(fs.readFileSync(path.join(dir, 'data.json'), 'utf8'));
data.palettes = JSON.parse(fs.readFileSync(path.join(dir, 'palettes.json'), 'utf8'));
fs.writeFileSync(path.join(dir, 'data.js'), `/* generated by tools/build-assets.mjs: data.json + palettes.json */\nwindow.AG_DATA=${JSON.stringify(data)};\n`);
// fonts as data URIs: a font fetched from file:// is blocked by CORS, so this keeps double-click viewing working
const face = (fam, file, style) => `@font-face{font-family:'${fam}';src:url(data:font/woff2;base64,${fs.readFileSync(path.join(dir, 'fonts', file)).toString('base64')}) format('woff2');font-weight:100 1000;font-style:${style};font-display:swap}`;
fs.writeFileSync(path.join(dir, 'fonts.css'), '/* generated by tools/build-assets.mjs from fonts/*.woff2 (Fraunces and DM Sans, SIL OFL) */\n' + [face('Fraunces', 'fraunces-variable.woff2', 'normal'), face('Fraunces', 'fraunces-italic-variable.woff2', 'italic'), face('DM Sans', 'dm-sans-variable.woff2', 'normal')].join('\n') + '\n');
console.log(symbols.length, 'symbols;', 'data.js', fs.statSync(path.join(dir, 'data.js')).size, 'bytes');

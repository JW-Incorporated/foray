#!/usr/bin/env node
/* Put the REAL app icon into the generated iOS asset catalog.
 *
 * WHY THIS EXISTS (2026-09-03)
 * Nothing wired 4a's icon into the app bundle. `cap add ios` generates
 * Capacitor's own placeholder `Assets.xcassets/AppIcon.appiconset`, and
 * `.github/workflows/ios-build.yml` archived it as-is — so a build went to
 * TestFlight today wearing Capacitor's default icon. `tools/brand/build-icons.mjs`
 * says it plainly in a comment beside `icon-1024.png`: "App Store marketing icon
 * (submission only; not shipped in the bundle)". Accurate, and the gap. This
 * script is the missing step, and it is a script rather than a `HUMAN-ACTIONS.md`
 * line for the same reason `inject-background-audio.mjs` is: `mobile/ios/` is
 * generated on every run and never committed, so a human doing it by hand does it
 * again every time, and forgets once.
 *
 * THE ASSET CATALOG IS THE ONLY PATH, INCLUDING FOR THE PUBLIC LISTING.
 * Apple removed the App Store Connect icon-upload field in Xcode 14; App Store
 * Connect now EXTRACTS the listing icon from the uploaded binary's asset
 * catalog — the 1024x1024 universal slot below. So the home screen, the
 * TestFlight tile and the public product page all read the same file this script
 * writes, there is no dashboard to fix it in, and an already-uploaded build
 * cannot be corrected. (Google Play DOES take a manual upload, which is what
 * `docs/store/play/app-icon-512.png` is; iOS has no equivalent. Do not reason
 * from one to the other.) That is why `assertMarketingSlot` refuses a catalog
 * with no 1024 entry rather than writing the smaller slots and reporting
 * success.
 *
 * WHY IT READS `Contents.json` INSTEAD OF WRITING A KNOWN FILENAME
 * The obvious version of this is `cp icon-1024.png .../AppIcon-512@2x.png`. That
 * filename is Capacitor 8's; it was different in 5, and it is a TEMPLATE, so it
 * changes when they change it. A copy to a name the catalog no longer declares
 * leaves the placeholder in place, compiles, archives, uploads, and ships the
 * wrong icon with every check green — the "fails green" shape this repo keeps
 * getting burned by (`tools/ci/run-suites.mjs`'s header, and
 * `inject-background-audio.mjs`'s). So the catalog's own manifest is the source
 * of truth for what to write, and an image it declares that we cannot produce is
 * an ERROR rather than a skip.
 *
 * WHY IT VALIDATES THE SOURCE FIRST
 * **The App Store rejects an app icon that carries an alpha channel.** Today
 * `icon-1024.png` is 1024x1024, colour type 2, no `tRNS` — but that is a property
 * of a GENERATED file (`build-icons.mjs` passes `{ rgb: true }`), and a future
 * regeneration that loses that option produces a perfectly good-looking icon that
 * Apple's validator rejects after the archive, the upload and the wait. Asserting
 * it here moves that failure to a Windows machine with no Mac. Same for the
 * dimensions: iOS wants exactly 1024x1024 for the universal marketing icon.
 *
 * WHY IT RE-READS ITS OWN OUTPUT
 * Same argument as `assertModePresent` in `inject-background-audio.mjs`: without
 * it every failure below degrades to "wrote nothing and reported success". The
 * check that matters most is `--check`, and it is deliberately NOT "the file
 * exists" — the PLACEHOLDER exists, and it is also 1024x1024. It compares bytes.
 *
 * USAGE
 *   node tools/mobile/inject-app-icon.mjs <AppIcon.appiconset>
 *   node tools/mobile/inject-app-icon.mjs <AppIcon.appiconset> --check
 *   node tools/mobile/inject-app-icon.mjs <AppIcon.appiconset> --source <png>
 * Any other argument is an error, not an ignored flag (same rule as
 * run-suites.mjs, prepare-webdir.mjs and inject-background-audio.mjs).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { header, decode, encode } from "../brand/png.mjs";
import { resizeArea } from "../brand/build-icons.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(HERE, "..", "..");

/** The master the bundle icon comes from. Generated by
 *  `tools/brand/build-icons.mjs` from `tools/brand/4a-logo.png`; committed at
 *  the repo root because the PWA manifest and the store listings read it too. */
export const DEFAULT_SOURCE = path.join(REPO_ROOT, "icon-1024.png");

/** Apple's universal marketing icon is exactly this, and nothing else. */
export const SOURCE_PX = 1024;

export class IconError extends Error {}

/* ------------------------------------------------------- the source PNG */

/**
 * Refuse a source icon the App Store would reject, BEFORE it reaches a bundle.
 *
 * EXPORTED SO IT CAN BE TESTED DIRECTLY, for the reason `assertModePresent`
 * carries: a validation that lives inline at the top of the writer can be
 * deleted in one line with every test still green.
 *
 * @returns {{width:number,height:number,colour:number}}
 */
export function assertAppStoreLegalSource(buf, label = "the source icon") {
  if (!Buffer.isBuffer(buf) || buf.length === 0) {
    throw new IconError(`${label} is empty`);
  }
  let h;
  try {
    h = header(buf);
  } catch (e) {
    throw new IconError(`${label} is not a readable PNG: ${e.message}`);
  }
  if (h.width !== SOURCE_PX || h.height !== SOURCE_PX) {
    throw new IconError(
      `${label} is ${h.width}x${h.height}; the iOS marketing icon must be exactly ` +
        `${SOURCE_PX}x${SOURCE_PX}. Regenerate it with tools/brand/build-icons.mjs.`
    );
  }
  /* THE ONE THAT COSTS A RELEASE CYCLE. Colour type 6 is RGBA and 4 is
     grey+alpha; both carry an alpha channel even when every pixel is opaque, and
     App Store Connect rejects the icon on the channel, not on the pixels. */
  if (h.colour === 4 || h.colour === 6) {
    throw new IconError(
      `${label} has colour type ${h.colour}, which carries an ALPHA CHANNEL. The App Store ` +
        `rejects an app icon with one, however opaque it looks. tools/brand/png.mjs's ` +
        `encode() takes { rgb: true } for exactly this; something regenerated the icon ` +
        `without it.`
    );
  }
  if (h.colour !== 2) {
    throw new IconError(
      `${label} has colour type ${h.colour}; the bundle icon must be colour type 2 ` +
        `(8-bit RGB, no alpha, no palette). Regenerate it with tools/brand/build-icons.mjs.`
    );
  }
  /* `tRNS` adds transparency to a colour-type-2 image without changing its
     colour type, so the check above does not cover it. */
  if (h.transparency) {
    throw new IconError(
      `${label} carries a tRNS chunk, which makes one colour transparent. That is an alpha ` +
        `channel by another name and the App Store rejects it the same way.`
    );
  }
  if (h.depth !== 8) throw new IconError(`${label} is ${h.depth}-bit; iOS icons are 8-bit`);
  if (h.interlace !== 0) throw new IconError(`${label} is interlaced; iOS icons are not`);
  return { width: h.width, height: h.height, colour: h.colour };
}

/* -------------------------------------------------- the catalog's manifest */

/** `"60x60"` / `"83.5x83.5"` -> the number, or null if it is not a square size. */
function squareSize(size) {
  const m = /^(\d+(?:\.\d+)?)x(\d+(?:\.\d+)?)$/.exec(String(size ?? "").trim());
  if (!m) return null;
  if (m[1] !== m[2]) return null;
  return Number(m[1]);
}

/** `"2x"` -> 2. Absent means 1 (the universal 1024 entry declares no scale). */
function scaleFactor(scale) {
  if (scale === undefined || scale === null || scale === "") return 1;
  const m = /^(\d+)x$/.exec(String(scale).trim());
  return m ? Number(m[1]) : null;
}

/**
 * Every image the catalog declares a FILE for, with the pixel size that file
 * must be. Entries with no `filename` are unassigned slots — Xcode's own way of
 * saying "nothing here" — and are counted, not written and not refused.
 *
 * @returns {{images: {filename:string, px:number, size:string, scale:string|null}[], unassigned: number}}
 */
export function declaredIcons(contentsSrc) {
  let doc;
  try {
    doc = JSON.parse(contentsSrc);
  } catch (e) {
    throw new IconError(`Contents.json is not valid JSON: ${e.message}`);
  }
  if (!doc || typeof doc !== "object" || Array.isArray(doc)) {
    throw new IconError("Contents.json is not a JSON object — this is not an asset catalog");
  }
  if (!Array.isArray(doc.images)) {
    throw new IconError('Contents.json has no "images" array — this is not an .appiconset');
  }

  const images = [];
  const byName = new Map();
  let unassigned = 0;
  for (const [i, img] of doc.images.entries()) {
    if (!img || typeof img !== "object") {
      throw new IconError(`Contents.json images[${i}] is not an object`);
    }
    const filename = img.filename;
    if (filename === undefined || filename === null || filename === "") {
      unassigned++;
      continue;
    }
    if (typeof filename !== "string") {
      throw new IconError(`Contents.json images[${i}].filename is not a string`);
    }
    /* A filename is a name, not a path. Xcode never nests one, and honouring a
       `../` here would let a generated file choose where this script writes. */
    if (filename.includes("/") || filename.includes("\\") || filename === "." || filename === "..") {
      throw new IconError(
        `Contents.json images[${i}].filename is ${JSON.stringify(filename)}, which is a path ` +
          `rather than a name. Refusing to write outside the .appiconset.`
      );
    }
    const size = squareSize(img.size);
    if (size === null) {
      throw new IconError(
        `Contents.json images[${i}] (${filename}) declares size ${JSON.stringify(img.size)}, which ` +
          `is not a square WxH. This script renders from a square master and will not stretch it.`
      );
    }
    const scale = scaleFactor(img.scale);
    if (scale === null) {
      throw new IconError(
        `Contents.json images[${i}] (${filename}) declares scale ${JSON.stringify(img.scale)}, ` +
          `which is not an Nx factor.`
      );
    }
    const px = size * scale;
    if (!Number.isInteger(px) || px < 1) {
      throw new IconError(
        `Contents.json images[${i}] (${filename}) works out to ${px} pixels ` +
          `(${img.size} at ${img.scale ?? "1x"}), which is not a whole number of pixels.`
      );
    }
    const seen = byName.get(filename);
    if (seen !== undefined && seen !== px) {
      /* One file cannot be two sizes. Whichever entry we honoured, the other
         slot would render a wrongly-sized icon and nothing would say so. */
      throw new IconError(
        `Contents.json declares ${filename} at both ${seen}px and ${px}px. One file cannot ` +
          `satisfy both slots; fix the catalog.`
      );
    }
    if (seen === undefined) {
      byName.set(filename, px);
      images.push({ filename, px, size: String(img.size), scale: img.scale ?? null });
    }
  }

  if (!images.length) {
    throw new IconError(
      `Contents.json declares ${unassigned} image slot(s) and not one filename, so this script ` +
        `would write nothing and report success. Refusing.`
    );
  }
  return { images, unassigned };
}

/* --------------------------------------------------------------- rendering */

/**
 * The bytes for one declared image.
 *
 * At `SOURCE_PX` this is the source file VERBATIM — not a re-encode. The
 * committed `icon-1024.png` is what the App Store listing shows, and shipping a
 * re-compressed near-copy of it inside the bundle would mean two files that are
 * "the icon" and differ, with nothing able to say which is right.
 *
 * Below it, the master is area-averaged down with `build-icons.mjs`'s own
 * `resizeArea` (exported there for reuse for exactly this reason) and written as
 * colour type 2, so a downscaled slot has no alpha channel either.
 *
 * ABOVE IT, THROW. Upscaling a 1024 master to 2048 produces a soft icon that
 * looks like a bad export, and no store slot asks for one.
 */
export function renderIconBytes(px, sourceBuf, decoded = null) {
  if (px === SOURCE_PX) return sourceBuf;
  if (px > SOURCE_PX) {
    throw new IconError(
      `the catalog wants a ${px}px icon and the master is only ${SOURCE_PX}px. This script will ` +
        `not upscale — regenerate a larger master with tools/brand/build-icons.mjs instead.`
    );
  }
  const img = decoded ?? decode(sourceBuf);
  const small = resizeArea(img, { x0: 0, y0: 0, w: img.width, h: img.height }, px, px);
  return encode(small, { rgb: true });
}

/**
 * Refuse a catalog with no 1024x1024 slot.
 *
 * NOT A STYLE RULE. App Store Connect extracts the PUBLIC LISTING icon from the
 * uploaded binary's asset catalog (the upload field was removed in Xcode 14), and
 * the slot it reads is this one. A catalog that declares only home-screen sizes
 * would let this script write four small icons, report success, build, upload —
 * and produce a store listing with no icon of ours anywhere, unfixable without a
 * new build. So it is an error here, on a machine with no Mac, rather than a
 * rejection after the archive.
 *
 * EXPORTED so it can be tested directly, for the reason `assertModePresent`
 * carries: a guard folded into the writer can be deleted in one line with every
 * other test still green.
 */
export function assertMarketingSlot(images) {
  if (!images.some((i) => i.px === SOURCE_PX)) {
    throw new IconError(
      `Contents.json declares no ${SOURCE_PX}x${SOURCE_PX} image (it has: ` +
        `${images.map((i) => `${i.filename} ${i.px}px`).join(", ")}). App Store Connect reads the ` +
        `PUBLIC LISTING icon out of that slot in the uploaded binary — there is no manual upload ` +
        `on iOS — so a build without it ships a listing with no icon. Refusing to write a ` +
        `partial set.`
    );
  }
  return images;
}

/**
 * What to write, for a given catalog and master. Pure: no filesystem.
 *
 * @returns {{filename:string, px:number, bytes:Buffer}[]}
 */
export function planAppIcon(contentsSrc, sourceBuf) {
  assertAppStoreLegalSource(sourceBuf);
  const { images } = declaredIcons(contentsSrc);
  assertMarketingSlot(images);
  let decoded = null;
  return images.map(({ filename, px }) => {
    if (px !== SOURCE_PX && !decoded) decoded = decode(sourceBuf);
    return { filename, px, bytes: renderIconBytes(px, sourceBuf, decoded) };
  });
}

/* --------------------------------------------------------------- the write */

function readCatalog(dir) {
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) {
    throw new IconError(
      `${dir} is not a directory. Run \`npm run add:ios\` in mobile/ first — this script edits ` +
        `the GENERATED project, which is not committed.`
    );
  }
  const contents = path.join(dir, "Contents.json");
  if (!fs.existsSync(contents)) {
    throw new IconError(`${contents} does not exist, so this is not an .appiconset`);
  }
  return fs.readFileSync(contents, "utf8");
}

/**
 * Assert every planned icon is REALLY on disk, byte-for-byte, and is still an
 * App-Store-legal PNG of the right size.
 *
 * EXPORTED AND NAMED, like `assertModePresent`, because this is the guard whose
 * silent removal turns every failure above into "wrote nothing, exit 0". Note
 * what it does NOT do: check that the file exists. Capacitor's PLACEHOLDER
 * exists and is also 1024x1024, so existence is exactly the check that would
 * pass on the bug this script was written for.
 *
 * MUTATION: change the `Buffer.compare` below to always return 0 — the
 * "--check refuses the Capacitor placeholder" test fails.
 */
export function assertIconsLanded(dir, plan) {
  if (!plan.length) throw new IconError("nothing was planned, so there is nothing to verify");
  for (const { filename, px, bytes } of plan) {
    const at = path.join(dir, filename);
    if (!fs.existsSync(at)) {
      throw new IconError(`${filename} is declared by Contents.json but is not in the catalog`);
    }
    const got = fs.readFileSync(at);
    if (Buffer.compare(got, bytes) !== 0) {
      throw new IconError(
        `${filename} is not our icon: ${got.length} bytes on disk against ${bytes.length} ` +
          `expected. This is Capacitor's placeholder, or a stale copy — run this script ` +
          `without --check.`
      );
    }
    const h = header(got);
    if (h.width !== px || h.height !== px) {
      throw new IconError(`${filename} is ${h.width}x${h.height} on disk but the catalog wants ${px}px`);
    }
    if (h.colour === 4 || h.colour === 6 || h.transparency) {
      throw new IconError(`${filename} carries an alpha channel; the App Store rejects it`);
    }
  }
  return plan.map((p) => p.filename);
}

/**
 * Write the icon into the generated `AppIcon.appiconset`.
 *
 * Idempotent, like `injectBackgroundAudio`, because CI re-runs and `cap sync`
 * regenerates: a file whose bytes already match is left alone rather than
 * rewritten.
 *
 * @returns {{changed:boolean, reason:string, wrote:string[], files:string[]}}
 */
export function injectAppIcon(dir, sourcePath = DEFAULT_SOURCE) {
  const contentsSrc = readCatalog(dir);
  if (!fs.existsSync(sourcePath)) {
    throw new IconError(`the source icon ${sourcePath} does not exist`);
  }
  const plan = planAppIcon(contentsSrc, fs.readFileSync(sourcePath));

  const wrote = [];
  for (const { filename, bytes } of plan) {
    const at = path.join(dir, filename);
    if (fs.existsSync(at) && Buffer.compare(fs.readFileSync(at), bytes) === 0) continue;
    fs.writeFileSync(at, bytes);
    wrote.push(filename);
  }

  /* THE ANTI-FAILS-GREEN CHECK — re-read from disk, do not trust the writes. */
  const files = assertIconsLanded(dir, plan);
  return {
    changed: wrote.length > 0,
    reason: wrote.length
      ? `wrote ${wrote.join(", ")}`
      : `${files.join(", ")} already matched the master`,
    wrote,
    files,
  };
}

/** `--check`: the catalog already holds our icon, byte-for-byte. Throws if not. */
export function checkAppIcon(dir, sourcePath = DEFAULT_SOURCE) {
  const contentsSrc = readCatalog(dir);
  if (!fs.existsSync(sourcePath)) {
    throw new IconError(`the source icon ${sourcePath} does not exist`);
  }
  return assertIconsLanded(dir, planAppIcon(contentsSrc, fs.readFileSync(sourcePath)));
}

/* --------------------------------------------------------------------- main */

const USAGE =
  "Usage: node tools/mobile/inject-app-icon.mjs <AppIcon.appiconset> [--check] [--source icon-1024.png]";

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const argv = process.argv.slice(2);
  let dir = null;
  let source = DEFAULT_SOURCE;
  let checkOnly = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") checkOnly = true;
    else if (argv[i] === "--source") {
      source = argv[++i];
      /* A flag is never a value — the same hole `--mode --check` opened in
         inject-background-audio.mjs. */
      if (!source || source.startsWith("-")) {
        console.error(`--source needs a value, got ${source === undefined ? "nothing" : source}`);
        process.exit(2);
      }
    } else if (!argv[i].startsWith("-") && dir === null) dir = argv[i];
    else {
      console.error(`Unknown argument: ${argv[i]}`);
      console.error(USAGE);
      process.exit(2);
    }
  }
  if (!dir) {
    console.error(USAGE);
    process.exit(2);
  }

  try {
    if (checkOnly) {
      const files = checkAppIcon(dir, source);
      console.log(`${dir}: ${files.join(", ")} match ${path.relative(REPO_ROOT, source) || source}`);
    } else {
      const r = injectAppIcon(dir, source);
      console.log(`${dir}: ${r.reason}`);
    }
  } catch (e) {
    console.error(`inject-app-icon failed: ${e.message}`);
    process.exit(1);
  }
}

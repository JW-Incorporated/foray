test("app-icon-512.png is 512x512 and 32-bit RGBA, which is the half of Play's spec the shipped icon fails", () => {
  /* THE REJECTION, restated as an assertion. `icon-512.png` is the right size
     and the wrong colour type: Play wants "32-bit PNG (with alpha)" and it is
     24-bit RGB. That is the single most likely way this submission bounces
     again, and it is invisible in every image viewer.

     NOT caught by the pixel test above, and the reason is worth knowing:
     `decode()` normalises colour type 2 and 6 to the same RGBA buffer, so an
     opaque alpha channel and no alpha channel at all compare equal. Colour
     type is the only thing that sees the difference. Same trap the banner's
     rgb:false mutation documents, running in the opposite direction. */
  const h = pngHeader(read(ICON_OUTPUT));
  assert.equal(h.width, PLAY.ICON_PX, "icon width");
  assert.equal(h.height, PLAY.ICON_PX, "icon height");
  assert.equal(ICON_SIZE, PLAY.ICON_PX, "the generator's SIZE must be Play's");
  assert.equal(h.depth, 8, "bit depth");
  assert.equal(h.colour, PLAY.ICON_COLOUR, "must be RGBA (colour type 6): Play requires a 32-bit PNG");

  /* 32-bit, but nothing transparent. Play renders a transparent asset over its
     own UI background colour, which would put the mark on whatever grey the
     store is using that month instead of on the brand cream. */
  const { data } = decode(read(ICON_OUTPUT));
  for (let i = 3; i < data.length; i += 4) {
    if (data[i] !== 255) assert.fail("the Play icon has transparent pixels; the alpha channel must be present and fully opaque");
  }
});


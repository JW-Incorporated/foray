test("README.md names every asset in the directory", () => {
  /* The README is the whole deliverable for the person filling in the form: if
     an asset is in the folder and not in the README, it is invisible, and if it
     is in the README and not in the folder, they go looking for it. Both
     directions, so adding a fifth screenshot without documenting it is red. */
  const readme = text(`${DIR}/README.md`);
  const assets = fs.readdirSync(path.join(ROOT, DIR)).filter((f) => f !== "README.md");
  assert.ok(assets.length > 0, `${DIR} has no assets`);
  for (const f of assets) {
    assert.ok(readme.includes(f), `README.md does not mention ${f}`);
  }
  /* The reverse direction is scoped to THIS package's own naming, not to every
     filename in the prose. The README legitimately points at things that live
     elsewhere -- `icon-512.png` is in the repo root, because that one is the
     icon the APP ships (and the App Store's, which is why it carries no alpha);
     Play's own icon is `app-icon-512.png` and is in this folder. What must not
     happen is the README promising `screenshot-5-…` that nobody committed. */
  const PACKAGE_ASSET = /^(feature-graphic\.png|app-icon-512\.png|screenshot-\d+-[\w-]+\.(?:jpg|png)|[\w-]*description\.txt)$/;
  for (const named of readme.match(/[\w-]+\.(?:png|jpg|txt)/g) || []) {
    if (!PACKAGE_ASSET.test(named)) continue;
    assert.ok(assets.includes(named), `README.md points at ${named}, which is not in ${DIR}`);
  }
});


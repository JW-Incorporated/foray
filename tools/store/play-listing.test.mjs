/* ---------- the store icon: generated, and the one PNG here that wants alpha ---------- */

/** Ink bounding box of a decoded icon, using the generator's own two helpers so
    "what counts as ink" is one definition and not two. `background()` reads the
    four corners, which on a full-bleed icon are the cream ground by
    construction. */
function markBox(rel) {
  const img = decode(read(rel));
  return { img, box: inkBox(img, background(img)) };
}


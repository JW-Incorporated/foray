/* Dossier seeds: which pages a taxonomy node's dossier is built from.
 *
 * GV-30 (W3-19, docs/roadmap/generation-v2.md). Discovery uses NO search
 * model and no search API:
 *
 * - The node's label, as an English Wikipedia ARTICLE page title:
 *   https://en.wikipedia.org/wiki/<Label_with_underscores>.
 *   en.wikipedia.org/robots.txt (checked 2026-10-11) disallows /w/ and /api/
 *   for every agent, so the MediaWiki Action API and the REST API are out;
 *   /wiki/<Title> article pages are allowed. Every URL this module returns
 *   passes `assertSeedUrl`, which refuses any Wikipedia path outside /wiki/.
 * - tools/corpus/dossiers/seeds.json, committed and code-reviewed:
 *   {"<nodeId>": ["https://...", ...]}; keys starting with "_" are comments.
 *   A Wikipedia /wiki/ URL listed for a node OVERRIDES the label guess (the
 *   reviewer picked the right article, e.g. past a disambiguation page);
 *   any other URL is an EXTRA source added after it. Its URLs are chosen by
 *   hand or in a reviewed PR and never generated by a Claude call (OQ-06
 *   parks Claude-built dossiers).
 * - `--subjects <file>`: {"<benchmark subject>": ["https://...", ...]}. Each
 *   subject becomes its own dossier, node id `subject/<slug>`, built only
 *   from the listed URLs.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(HERE, "..", "..", "..");
export const SEEDS_PATH = path.join(HERE, "seeds.json");
export const TAXONOMY_PATH = path.join(REPO_ROOT, "data", "taxonomy.json");

export const WIKIPEDIA_HOST = "en.wikipedia.org";

export class SeedError extends Error {
  constructor(message) {
    super(message);
    this.name = "SeedError";
  }
}

const isWikipedia = (u) => u.hostname === "wikipedia.org" || u.hostname.endsWith(".wikipedia.org");

/** Throws unless `url` is an https URL the builder may request: on any
    Wikipedia host, only an article path /wiki/<Title> (never /w/, /api/ or
    anything else robots.txt or the card rules out). Returns the URL href. */
export function assertSeedUrl(url) {
  let u;
  try {
    u = new URL(url);
  } catch {
    throw new SeedError(`not a URL: ${url}`);
  }
  if (u.protocol !== "https:") throw new SeedError(`not https: ${url}`);
  if (isWikipedia(u)) {
    if (/^\/(?:w|api)(?:\/|$)/i.test(u.pathname)) {
      throw new SeedError(`Wikipedia /w/ and /api/ are disallowed by robots.txt: ${url}`);
    }
    if (!/^\/wiki\/[^/]/.test(u.pathname) || u.search) {
      throw new SeedError(`only Wikipedia article pages /wiki/<Title> are allowed: ${url}`);
    }
  }
  return u.href;
}

/** A page title -> its English Wikipedia article URL (spaces to underscores,
    everything else percent-encoded, so a title can never leave /wiki/). */
export function wikiUrlForTitle(title) {
  const t = String(title ?? "").trim().replace(/\s+/g, "_");
  if (!t || /^\.+$/.test(t)) throw new SeedError(`unusable page title: ${JSON.stringify(title)}`);
  const encoded = encodeURIComponent(t).replace(/%3A/gi, ":").replace(/%2C/gi, ",");
  return assertSeedUrl(`https://${WIKIPEDIA_HOST}/wiki/${encoded}`);
}

const isWikiArticle = (url) => {
  const u = new URL(url);
  return isWikipedia(u) && u.pathname.startsWith("/wiki/");
};

/** The seed URLs for one taxonomy node, in build order:
    the label guess (unless seeds.json overrides it with a Wikipedia
    article), then the node's seeds.json URLs. De-duplicated. */
export function titlesForNode(node, seeds = {}) {
  const listed = (seeds[node.id] ?? []).map(assertSeedUrl);
  const overridden = listed.some(isWikiArticle);
  const urls = overridden ? listed : [wikiUrlForTitle(node.label), ...listed];
  return [...new Set(urls)];
}

/** Parses and validates a seeds map: {"<nodeId>": [url]}; "_" keys are
    comments. With `nodeIds`, every key must be a known taxonomy node. */
export function parseSeeds(obj, { nodeIds = null, what = "seeds.json" } = {}) {
  if (!obj || typeof obj !== "object" || Array.isArray(obj)) throw new SeedError(`${what}: expected an object`);
  const out = {};
  for (const [key, urls] of Object.entries(obj)) {
    if (key.startsWith("_")) continue;
    if (nodeIds && !nodeIds.has(key)) throw new SeedError(`${what}: "${key}" is not a taxonomy node`);
    if (!Array.isArray(urls) || urls.some((u) => typeof u !== "string")) {
      throw new SeedError(`${what}: "${key}" must map to an array of URL strings`);
    }
    out[key] = urls.map((u) => {
      try {
        return assertSeedUrl(u);
      } catch (err) {
        throw new SeedError(`${what}: "${key}": ${err.message}`);
      }
    });
  }
  return out;
}

export function loadTaxonomyNodes(file = TAXONOMY_PATH) {
  const tax = JSON.parse(fs.readFileSync(file, "utf8"));
  return tax.nodes.map((n) => ({ id: n.id, label: n.label }));
}

export function loadSeeds(file = SEEDS_PATH, { nodeIds = null } = {}) {
  return parseSeeds(JSON.parse(fs.readFileSync(file, "utf8")), { nodeIds, what: path.basename(file) });
}

const slug = (s) =>
  String(s)
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");

/** A --subjects file -> build targets {id, label, urls}. */
export function subjectTargets(obj, { what = "--subjects file" } = {}) {
  const parsed = parseSeeds(obj, { what });
  const seen = new Map();
  return Object.entries(parsed).map(([subject, urls]) => {
    const s = slug(subject);
    if (!s) throw new SeedError(`${what}: subject "${subject}" has no usable slug`);
    const id = `subject/${s}`;
    if (seen.has(id)) throw new SeedError(`${what}: subjects "${seen.get(id)}" and "${subject}" share the id ${id}`);
    seen.set(id, subject);
    if (urls.length === 0) throw new SeedError(`${what}: subject "${subject}" lists no URL`);
    return { id, label: subject, urls };
  });
}
